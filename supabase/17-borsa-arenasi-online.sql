-- Pamuk Eller Borsa Arenası: gerçek kullanıcı hesapları, sezonlar ve sunucu tarafında doğrulanan sanal işlemler.
-- Bu modül yalnızca oyun/simülasyon verisidir; kişisel finans hesaplarıyla bağlantılı değildir.

create table if not exists public.arena_seasons (
  id bigint generated by default as identity primary key,
  name text not null,
  start_date timestamptz not null,
  end_date timestamptz not null,
  active boolean not null default false,
  created_at timestamptz not null default now(),
  constraint arena_seasons_dates_check check (end_date > start_date)
);
create unique index if not exists arena_one_active_season_idx on public.arena_seasons (active) where active = true;

create table if not exists public.arena_accounts (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  season_id bigint not null references public.arena_seasons(id) on delete cascade,
  username text not null,
  cash_balance numeric(18,2) not null default 100000,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint arena_accounts_balance_check check (cash_balance >= 0),
  constraint arena_accounts_user_season_key unique (user_id, season_id)
);
create unique index if not exists arena_accounts_username_season_idx on public.arena_accounts (season_id, lower(username));

create table if not exists public.arena_positions (
  id bigint generated by default as identity primary key,
  account_id uuid not null references public.arena_accounts(id) on delete cascade,
  symbol text not null,
  quantity numeric(18,4) not null check (quantity > 0),
  avg_price numeric(18,4) not null check (avg_price > 0),
  current_price numeric(18,4) not null check (current_price > 0),
  updated_at timestamptz not null default now(),
  constraint arena_positions_account_symbol_key unique (account_id, symbol)
);

create table if not exists public.arena_trades (
  id bigint generated by default as identity primary key,
  account_id uuid not null references public.arena_accounts(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  season_id bigint not null references public.arena_seasons(id) on delete cascade,
  symbol text not null,
  side text not null check (side in ('BUY','SELL')),
  quantity numeric(18,4) not null check (quantity > 0),
  price numeric(18,4) not null check (price > 0),
  total numeric(18,2) not null check (total > 0),
  created_at timestamptz not null default now()
);

create table if not exists public.arena_leaderboard (
  account_id uuid primary key references public.arena_accounts(id) on delete cascade,
  season_id bigint not null references public.arena_seasons(id) on delete cascade,
  username text not null,
  total_value numeric(18,2) not null default 100000 check (total_value >= 0),
  updated_at timestamptz not null default now()
);
create index if not exists arena_leaderboard_season_value_idx on public.arena_leaderboard (season_id, total_value desc);
create index if not exists arena_trades_account_created_idx on public.arena_trades (account_id, created_at desc);
create index if not exists arena_trades_user_id_idx on public.arena_trades (user_id);
create index if not exists arena_trades_season_id_idx on public.arena_trades (season_id);
create index if not exists arena_positions_account_idx on public.arena_positions (account_id);

alter table public.arena_seasons enable row level security;
alter table public.arena_accounts enable row level security;
alter table public.arena_positions enable row level security;
alter table public.arena_trades enable row level security;
alter table public.arena_leaderboard enable row level security;

drop policy if exists "arena_seasons_public_read" on public.arena_seasons;
create policy "arena_seasons_public_read" on public.arena_seasons for select to anon, authenticated using (true);
drop policy if exists "arena_leaderboard_public_read" on public.arena_leaderboard;
create policy "arena_leaderboard_public_read" on public.arena_leaderboard for select to anon, authenticated using (true);
drop policy if exists "arena_accounts_deny_client_access" on public.arena_accounts;
create policy "arena_accounts_deny_client_access" on public.arena_accounts for all to anon, authenticated using (false) with check (false);
drop policy if exists "arena_positions_deny_client_access" on public.arena_positions;
create policy "arena_positions_deny_client_access" on public.arena_positions for all to anon, authenticated using (false) with check (false);
drop policy if exists "arena_trades_deny_client_access" on public.arena_trades;
create policy "arena_trades_deny_client_access" on public.arena_trades for all to anon, authenticated using (false) with check (false);

revoke all on public.arena_seasons, public.arena_accounts, public.arena_positions, public.arena_trades, public.arena_leaderboard from anon, authenticated;
grant select on public.arena_seasons, public.arena_leaderboard to anon, authenticated;
grant all on public.arena_seasons, public.arena_accounts, public.arena_positions, public.arena_trades, public.arena_leaderboard to service_role;
revoke all on sequence public.arena_seasons_id_seq, public.arena_positions_id_seq, public.arena_trades_id_seq from anon, authenticated;
grant usage, select on sequence public.arena_seasons_id_seq, public.arena_positions_id_seq, public.arena_trades_id_seq to service_role;

create or replace function public.arena_ensure_account(p_user_id uuid, p_username text default null)
returns jsonb language plpgsql security definer set search_path = public, pg_temp as $$
declare
  v_season public.arena_seasons%rowtype;
  v_account public.arena_accounts%rowtype;
  v_username text;
  v_suffix text;
begin
  if p_user_id is null then raise exception 'AUTH_REQUIRED'; end if;
  perform pg_advisory_xact_lock(hashtext('pamuk-eller-arena-season'));
  update public.arena_seasons set active = false where active = true and end_date <= now();
  select * into v_season from public.arena_seasons where active = true order by start_date desc limit 1 for update;
  if not found then
    insert into public.arena_seasons(name,start_date,end_date,active)
    values ('Sezon ' || to_char(now() at time zone 'Europe/Istanbul','YYYY-MM-DD'),now(),now() + interval '30 days',true)
    returning * into v_season;
  end if;

  v_username := left(regexp_replace(trim(coalesce(p_username,'')), '[^[:alnum:]_.-]', '', 'g'), 24);
  if length(v_username) < 3 then v_username := 'Oyuncu-' || substr(replace(p_user_id::text,'-',''),1,8); end if;
  v_suffix := substr(replace(p_user_id::text,'-',''),1,5);
  if exists (select 1 from public.arena_accounts a where a.season_id=v_season.id and lower(a.username)=lower(v_username) and a.user_id<>p_user_id) then
    v_username := left(v_username,18) || '-' || v_suffix;
  end if;

  insert into public.arena_accounts(user_id,season_id,username) values (p_user_id,v_season.id,v_username)
  on conflict (user_id,season_id) do update set updated_at=now() returning * into v_account;

  insert into public.arena_leaderboard(account_id,season_id,username,total_value)
  values (v_account.id,v_account.season_id,v_account.username,v_account.cash_balance)
  on conflict (account_id) do update set username=excluded.username,updated_at=now();

  return jsonb_build_object('account_id',v_account.id,'season_id',v_season.id,'username',v_account.username,'cash_balance',v_account.cash_balance);
end;
$$;

create or replace function public.arena_sync_quotes(p_quotes jsonb)
returns integer language plpgsql security definer set search_path = public, pg_temp as $$
declare v_count integer;
begin
  if jsonb_typeof(p_quotes)<>'array' or jsonb_array_length(p_quotes)>50 then raise exception 'INVALID_QUOTES'; end if;
  update public.arena_positions p set current_price=q.price,updated_at=now()
  from jsonb_to_recordset(p_quotes) as q(symbol text,price numeric)
  where p.symbol=q.symbol and q.price>0 and q.price<=1000000000;
  get diagnostics v_count=row_count;
  update public.arena_leaderboard l
  set total_value=round(a.cash_balance+coalesce((select sum(p.quantity*p.current_price) from public.arena_positions p where p.account_id=a.id),0),2),
      username=a.username,updated_at=now()
  from public.arena_accounts a join public.arena_seasons s on s.id=a.season_id and s.active=true
  where l.account_id=a.id;
  return v_count;
end;
$$;

create or replace function public.arena_execute_trade(p_user_id uuid,p_symbol text,p_side text,p_quantity numeric,p_price numeric)
returns jsonb language plpgsql security definer set search_path = public, pg_temp as $$
declare
  v_season_id bigint;
  v_account public.arena_accounts%rowtype;
  v_position public.arena_positions%rowtype;
  v_total numeric(18,2);
  v_value numeric(18,2);
begin
  if p_user_id is null then raise exception 'AUTH_REQUIRED'; end if;
  if p_symbol is null or p_symbol !~ '^[A-Z0-9.]{2,15}$' then raise exception 'INVALID_SYMBOL'; end if;
  if p_side not in ('BUY','SELL') then raise exception 'INVALID_SIDE'; end if;
  if p_quantity is null or p_quantity<=0 or p_quantity>100000 or p_quantity<>trunc(p_quantity) then raise exception 'INVALID_QUANTITY'; end if;
  if p_price is null or p_price<=0 or p_price>1000000000 then raise exception 'INVALID_PRICE'; end if;

  perform public.arena_ensure_account(p_user_id,null);
  select id into v_season_id from public.arena_seasons where active=true and end_date>now() order by start_date desc limit 1;
  select * into v_account from public.arena_accounts where user_id=p_user_id and season_id=v_season_id for update;
  if not found then raise exception 'ARENA_ACCOUNT_NOT_FOUND'; end if;

  v_total:=round(p_quantity*p_price,2);
  if v_total<=0 then raise exception 'INVALID_TOTAL'; end if;

  if p_side='BUY' then
    if v_account.cash_balance<v_total then raise exception 'INSUFFICIENT_BALANCE'; end if;
    update public.arena_accounts set cash_balance=cash_balance-v_total,updated_at=now() where id=v_account.id returning * into v_account;
    insert into public.arena_positions(account_id,symbol,quantity,avg_price,current_price) values(v_account.id,p_symbol,p_quantity,p_price,p_price)
    on conflict(account_id,symbol) do update set
      avg_price=round((public.arena_positions.avg_price*public.arena_positions.quantity+excluded.avg_price*excluded.quantity)/(public.arena_positions.quantity+excluded.quantity),4),
      quantity=public.arena_positions.quantity+excluded.quantity,current_price=excluded.current_price,updated_at=now();
  else
    select * into v_position from public.arena_positions where account_id=v_account.id and symbol=p_symbol for update;
    if not found or v_position.quantity<p_quantity then raise exception 'INSUFFICIENT_SHARES'; end if;
    if v_position.quantity=p_quantity then delete from public.arena_positions where id=v_position.id;
    else update public.arena_positions set quantity=quantity-p_quantity,current_price=p_price,updated_at=now() where id=v_position.id; end if;
    update public.arena_accounts set cash_balance=cash_balance+v_total,updated_at=now() where id=v_account.id returning * into v_account;
  end if;

  insert into public.arena_trades(account_id,user_id,season_id,symbol,side,quantity,price,total)
  values(v_account.id,p_user_id,v_season_id,p_symbol,p_side,p_quantity,p_price,v_total);
  select round(v_account.cash_balance+coalesce(sum(quantity*current_price),0),2) into v_value from public.arena_positions where account_id=v_account.id;
  insert into public.arena_leaderboard(account_id,season_id,username,total_value,updated_at)
  values(v_account.id,v_season_id,v_account.username,v_value,now())
  on conflict(account_id) do update set username=excluded.username,total_value=excluded.total_value,updated_at=now();
  return jsonb_build_object('success',true,'cash_balance',v_account.cash_balance,'total_value',v_value,'trade_total',v_total);
end;
$$;

revoke all on function public.arena_ensure_account(uuid,text) from public,anon,authenticated;
revoke all on function public.arena_sync_quotes(jsonb) from public,anon,authenticated;
revoke all on function public.arena_execute_trade(uuid,text,text,numeric,numeric) from public,anon,authenticated;
grant execute on function public.arena_ensure_account(uuid,text) to service_role;
grant execute on function public.arena_sync_quotes(jsonb) to service_role;
grant execute on function public.arena_execute_trade(uuid,text,text,numeric,numeric) to service_role;
